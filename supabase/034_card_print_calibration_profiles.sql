-- Store shared, named printer calibration profiles for SPP card printing.
-- Run after 033_edit_student_entry_period.sql.
BEGIN;

CREATE TABLE IF NOT EXISTS public.spp_app_card_print_profiles (
  profile_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_name text NOT NULL,
  offset_x_mm numeric(5, 2) NOT NULL DEFAULT 0,
  offset_y_mm numeric(5, 2) NOT NULL DEFAULT 0,
  scale_percent numeric(5, 2) NOT NULL DEFAULT 100,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text NOT NULL,
  CONSTRAINT spp_app_card_print_profile_name_length_check
    CHECK (char_length(btrim(profile_name)) BETWEEN 1 AND 60),
  CONSTRAINT spp_app_card_print_profile_offset_x_check
    CHECK (offset_x_mm BETWEEN -10 AND 10),
  CONSTRAINT spp_app_card_print_profile_offset_y_check
    CHECK (offset_y_mm BETWEEN -10 AND 10),
  CONSTRAINT spp_app_card_print_profile_scale_check
    CHECK (scale_percent BETWEEN 95 AND 105)
);

CREATE UNIQUE INDEX IF NOT EXISTS spp_app_card_print_profiles_name_ci_uidx
  ON public.spp_app_card_print_profiles (lower(profile_name));

ALTER TABLE public.spp_app_card_print_profiles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.spp_app_card_print_profiles FROM PUBLIC, anon, authenticated;

INSERT INTO public.spp_app_card_print_profiles (
  profile_name, offset_x_mm, offset_y_mm, scale_percent, updated_by
)
VALUES ('Default', 0, 0, 100, 'system')
ON CONFLICT (lower(profile_name)) DO NOTHING;

CREATE OR REPLACE FUNCTION public.get_spp_card_print_profiles_v1(
  p_username text,
  p_password text,
  p_kdsek text
)
RETURNS TABLE (
  profile_name text,
  offset_x_mm numeric,
  offset_y_mm numeric,
  scale_percent numeric,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  PERFORM public.spp_app_assert_card_print_access(p_username, p_password, p_kdsek);

  RETURN QUERY
  SELECT profile.profile_name,
    profile.offset_x_mm,
    profile.offset_y_mm,
    profile.scale_percent,
    profile.updated_at
  FROM public.spp_app_card_print_profiles AS profile
  ORDER BY lower(profile.profile_name), profile.profile_name;
END;
$function$;

CREATE OR REPLACE FUNCTION public.save_spp_card_print_profile_v1(
  p_username text,
  p_password text,
  p_profile_name text,
  p_offset_x_mm numeric,
  p_offset_y_mm numeric,
  p_scale_percent numeric
)
RETURNS TABLE (
  profile_name text,
  offset_x_mm numeric,
  offset_y_mm numeric,
  scale_percent numeric,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_actor text := public.spp_app_assert_admin(p_username, p_password);
  v_profile_name text := btrim(COALESCE(p_profile_name, ''));
BEGIN
  IF char_length(v_profile_name) NOT BETWEEN 1 AND 60 THEN
    RAISE EXCEPTION 'Nama profil harus terdiri dari 1 sampai 60 karakter.'
      USING ERRCODE = '22023';
  END IF;
  IF p_offset_x_mm IS NULL OR p_offset_x_mm NOT BETWEEN -10 AND 10
     OR p_offset_y_mm IS NULL OR p_offset_y_mm NOT BETWEEN -10 AND 10 THEN
    RAISE EXCEPTION 'Offset horizontal dan vertikal harus berada antara -10 dan 10 mm.'
      USING ERRCODE = '22023';
  END IF;
  IF p_scale_percent IS NULL OR p_scale_percent NOT BETWEEN 95 AND 105 THEN
    RAISE EXCEPTION 'Skala harus berada antara 95 dan 105 persen.'
      USING ERRCODE = '22023';
  END IF;

  RETURN QUERY
  INSERT INTO public.spp_app_card_print_profiles AS current_profile (
    profile_name, offset_x_mm, offset_y_mm, scale_percent, updated_at, updated_by
  )
  VALUES (
    v_profile_name,
    p_offset_x_mm,
    p_offset_y_mm,
    p_scale_percent,
    now(),
    v_actor
  )
  ON CONFLICT (lower(profile_name)) DO UPDATE
  SET profile_name = EXCLUDED.profile_name,
      offset_x_mm = EXCLUDED.offset_x_mm,
      offset_y_mm = EXCLUDED.offset_y_mm,
      scale_percent = EXCLUDED.scale_percent,
      updated_at = EXCLUDED.updated_at,
      updated_by = EXCLUDED.updated_by
  RETURNING current_profile.profile_name,
    current_profile.offset_x_mm,
    current_profile.offset_y_mm,
    current_profile.scale_percent,
    current_profile.updated_at;
END;
$function$;

REVOKE ALL ON FUNCTION public.get_spp_card_print_profiles_v1(text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_spp_card_print_profiles_v1(text, text, text) TO anon, authenticated;

REVOKE ALL ON FUNCTION public.save_spp_card_print_profile_v1(text, text, text, numeric, numeric, numeric)
  FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.save_spp_card_print_profile_v1(text, text, text, numeric, numeric, numeric)
  TO anon, authenticated;

COMMIT;
